# 6. type() - 자료형 확인하기
# ============================================================
print("--- type() 확인 ---")
# JS의 typeof와 비슷하지만, 더 정확한 타입을 알려줍니다.
# JS: typeof "안녕" → "string"  /  Python: type("안녕") → <class 'str'>
print(type("안녕"))       # <class 'str'>
print(type(42))           # <class 'int'>    (JS에는 int/float 구분 없이 number)
print(type(3.14))         # <class 'float'>  (JS에는 int/float 구분 없음!)
print(type(True))         # <class 'bool'>   (JS: true ← 소문자! Python: True ← 대문자!)
print(type(None))         # <class 'NoneType'> (JS의 null과 유사, undefined는 없음)



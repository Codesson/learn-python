# 3. 변수 (Variable)
# ============================================================
# 변수는 값을 저장하는 이름표입니다.
# 파이썬은 변수의 타입을 자동으로 판단합니다.
# JS와 달리 let, const, var 키워드가 없습니다. 그냥 이름 = 값!

name = "홍길동"          # 문자열(str)     JS: let name = "홍길동"
age = 25                 # 정수(int)       JS: let age = 25
height = 175.5           # 실수(float)     JS: let height = 175.5
is_student = True        # 불리언(bool)    JS: let isStudent = true  ← 소문자!

print("이름:", name)
print("나이:", age)
print("키:", height)
print("학생 여부:", is_student)

# 변수 값 변경하기
age = 26
print("내년 나이:", age)

# 여러 변수를 한 줄에 할당
x, y, z = 1, 2, 3
print("x =", x, ", y =", y, ", z =", z)

# 같은 값을 여러 변수에 할당
a = b = c = 0
print("a =", a, ", b =", b, ", c =", c)

print()



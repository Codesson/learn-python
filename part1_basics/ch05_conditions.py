# ============================================================
# JavaScript vs Python 비교 - 조건문
# ============================================================
#
#  JavaScript                      Python
#  ─────────────────────────────    ─────────────────────────────
#  if (조건) {                     if 조건:           ← 괄호 없어도 됨!
#    코드                              코드           ← 들여쓰기가 블록!
#  } else if (조건) {              elif 조건:         ← else if → elif
#    코드                              코드
#  } else {                        else:
#    코드                              코드
#  }                               (닫는 괄호 없음)
#
#  a ? b : c  (삼항)               b if a else c      (순서 주의!)
#  switch (val) { case: }          match val:          (3.10+)
#
#  핵심 차이:
#  1) 중괄호 {} 대신 콜론(:) + 들여쓰기로 블록 구분
#  2) else if → elif (붙여 쓰기)
#  3) 조건에 괄호()가 필수가 아님
#

# ============================================================
# 1. 기본 if 문
# ============================================================
print("=== 기본 if 문 ===")

temperature = 35

if temperature > 30:
    print(f"현재 기온: {temperature}°C")
    print("더운 날씨입니다! 수분을 충분히 섭취하세요.")

print()


# ============================================================
# 2. if-else 문
# ============================================================
print("=== if-else 문 ===")

age = 17

if age >= 18:
    print(f"나이: {age}세 → 성인입니다.")
else:
    print(f"나이: {age}세 → 미성년자입니다.")

print()


# ============================================================
# 3. if-elif-else 문
# ============================================================
print("=== if-elif-else 문 ===")

score = 85

if score >= 90:
    grade = "A"
elif score >= 80:
    grade = "B"
elif score >= 70:
    grade = "C"
elif score >= 60:
    grade = "D"
else:
    grade = "F"

print(f"점수: {score} → 학점: {grade}")

print()


# ============================================================
# 4. 중첩 조건문
# ============================================================
print("=== 중첩 조건문 ===")

age = 25
has_id = True

if age >= 18:
    if has_id:
        print("입장 가능합니다.")
    else:
        print("신분증을 지참해 주세요.")
else:
    print("미성년자는 입장할 수 없습니다.")

print()


# ============================================================
# 5. 조건 표현식 (삼항 연산자)
# ============================================================
print("=== 조건 표현식 ===")

# 기본 형태: 값1 if 조건 else 값2
# JS: const status = age >= 18 ? "성인" : "미성년자"
# Python: status = "성인" if age >= 18 else "미성년자"
# 순서가 다릅니다! Python은 "참값 if 조건 else 거짓값"
age = 20
status = "성인" if age >= 18 else "미성년자"
print(f"나이: {age} → {status}")

# 짝수/홀수 판별
number = 7
result = "짝수" if number % 2 == 0 else "홀수"
print(f"{number}은(는) {result}입니다.")

# 절댓값 구하기
x = -5
abs_x = x if x >= 0 else -x
print(f"|{x}| = {abs_x}")

print()


# ============================================================
# 6. 논리 연산자와 조건문
# ============================================================
print("=== 논리 연산자 활용 ===")

# and: 모든 조건이 참일 때
username = "admin"
password = "1234"

if username == "admin" and password == "1234":
    print("로그인 성공!")
else:
    print("로그인 실패!")

# or: 하나라도 참일 때
day = "토요일"
if day == "토요일" or day == "일요일":
    print(f"{day}은 주말입니다. 쉬세요!")
else:
    print(f"{day}은 평일입니다.")

# not: 조건 반전
is_raining = False
if not is_raining:
    print("비가 오지 않습니다. 산책하세요!")

print()


# ============================================================
# 7. in 연산자와 조건문
# ============================================================
print("=== in 연산자 활용 ===")

favorite_fruits = ["사과", "바나나", "딸기"]
fruit = "바나나"

if fruit in favorite_fruits:
    print(f"{fruit}은(는) 좋아하는 과일 목록에 있습니다!")
else:
    print(f"{fruit}은(는) 목록에 없습니다.")

# 문자열에서도 사용
email = "user@example.com"
if "@" in email:
    print(f"'{email}'은(는) 유효한 이메일 형식입니다.")

print()


# ============================================================
# 8. 실전 예제: 간단한 계산기
# ============================================================
print("=== 실전 예제: 계산기 ===")

num1 = 10
num2 = 3
operator = "+"

if operator == "+":
    result = num1 + num2
elif operator == "-":
    result = num1 - num2
elif operator == "*":
    result = num1 * num2
elif operator == "/":
    if num2 != 0:
        result = num1 / num2
    else:
        result = "에러: 0으로 나눌 수 없습니다"
else:
    result = "에러: 알 수 없는 연산자"

print(f"{num1} {operator} {num2} = {result}")

print()


# ============================================================
# 9. match-case (파이썬 3.10+)
# ============================================================
print("=== match-case (3.10+) ===")

# JS의 switch-case와 유사하지만, break가 필요 없습니다!
# JS: switch(val) { case 200: ...; break; }
# Python: match val:  case 200: ...  (자동으로 break, fall-through 없음)
status_code = 404

match status_code:
    case 200:
        print("OK - 요청 성공")
    case 301:
        print("Moved Permanently - 리다이렉트")
    case 404:
        print("Not Found - 페이지를 찾을 수 없음")
    case 500:
        print("Internal Server Error - 서버 에러")
    case _:
        print(f"알 수 없는 상태 코드: {status_code}")


